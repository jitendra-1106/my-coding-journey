#include <iostream> // Includes the iostream library for input and output

int main()
{ // Program execution starts from main()

    std::cout << "HELLO WORLD"; // Prints "HELLO WORLD" on the screen
                                // cout is used for output
                                // std:: is the namespace prefix for the standard library
                                // << sends the text to cout

    return 0; // Ends the main() function successfully
}

