#include<iostream>
using namespace std;

int main(){
    int num1 , num2;

    cout<<"Enter the value of num1:\n";
    cin>>num1;

    cout<<"Enter the value of num2:\n";
    cin>>num2;

    cout<<"The value of num1 is "<<num1<<"\nThe value of num2 is "<<num2;
    return 0;
}    

/*
'<<' is called Insertion operator.
'>>' is called Extraction operator.
*/